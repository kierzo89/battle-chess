def _complete_segment(segment):
 data=bytearray()
 for at,part in sorted(segment.chunks):
  if not part or at!=len(data)or at+len(part)>segment.length:_fail('Arena CODE/CONST allocation has a hole/overlap/invalid write')
  data.extend(part)
 if len(data)!=segment.length or segment.unsupported_data:_fail('Arena CODE/CONST has reserved data or an uninitialized tail')
 return bytes(data)

