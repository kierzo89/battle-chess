"""Authenticate a whole compiler-owned CONST allocation for explicit relocation.

This is a comparison/ownership gate, never a generator or separate DATA-credit
backend. Strict OMF records and code relocation fields are not modified.
"""
from dataclasses import asdict
import hashlib
import json
from pathlib import Path

from omf import OMFError, OMFObject, _Cursor
from reference import validate_data_address, validate_expanded_read


class OwnedConstError(OMFError):
    pass


def _sha(data):
    return hashlib.sha256(data).hexdigest()


def validate(unit, obj, project, reference):
    """Return (placement descriptor, complete independent CONST bytes, proof).

    The descriptor has exactly segment/group/size/image_offset/data_address/
    rea_evidence keys. Size comes from a full initialized CONST SEGDEF, never
    an inferred label or expected function extent. Only the owning CODE's
    genuine OFFSET16 fields may refer to it; CONST itself has no relocations,
    publics, BSS, holes, or other allocations. Reference inputs only verify
    comparison placement and all independently generated bytes.
    """
    if not isinstance(obj, OMFObject) or not isinstance(unit, dict) or not isinstance(reference, dict):
        raise OwnedConstError('Owned CONST requires a strict OMF object and unit')
    if unit.get('owned_const_profile') is not None:
        from owned_literal_const16 import validate as validate_literal
        return validate_literal(unit, obj, project, reference)
    descriptor = unit.get('owned_const')
    keys = {'segment', 'group', 'size', 'image_offset', 'data_address', 'rea_evidence'}
    if not isinstance(descriptor, dict) or set(descriptor) != keys:
        raise OwnedConstError('Owned CONST requires an exact explicit descriptor')
    descriptor = dict(descriptor)
    for key in ('segment', 'group', 'size'):
        if type(descriptor[key]) is not int or not 0 < descriptor[key] <= 65535:
            raise OwnedConstError('Owned CONST indexes/size require positive 16-bit integers')
    if (unit.get('language') != 'c' or unit.get('backend') != 'msc500-omf'
            or not isinstance(descriptor['image_offset'], str)
            or not isinstance(descriptor['rea_evidence'], str)):
        raise OwnedConstError('Owned CONST requires explicit MSC5 C comparison metadata')
    try:
        info = obj.function_info(unit['symbol'])
    except (KeyError, OMFError) as exc:
        raise OwnedConstError('Owned CONST requires an independently bounded owner function') from exc
    if info['boundary'] != 'codeview3_procedure' or info['size'] != unit.get('size'):
        raise OwnedConstError('Owned CONST requires the full independent CodeView owner extent')
    const = obj.segments.get(descriptor['segment'])
    code = obj.segments.get(info['segment'])
    if (const is None or (const.name, const.class_name) != ('CONST', 'CONST')
            or const.length != descriptor['size'] or const.attributes != 0x48
            or code is None or code.class_name != 'CODE' or code.attributes != 0x48):
        raise OwnedConstError('Owned CONST requires a complete word-aligned PUBLIC CONST SEGDEF and CODE owner')
    if any(kind in (0xa2, 0xa3, 0xb0, 0xb8) for kind, _, _ in obj.records):
        raise OwnedConstError('Owned CONST rejects LIDATA and communal allocations')
    for other in obj.segments.values():
        if other.index in (const.index, code.index):
            continue
        debug = (other.name, other.class_name) in (('$$SYMBOLS', 'DEBSYM'), ('$$TYPES', 'DEBTYP'))
        zero_data = (other.name, other.class_name) in (('_DATA', 'DATA'), ('_BSS', 'BSS')) and not other.length
        if not debug and not zero_data:
            raise OwnedConstError('Owned CONST forbids other nondebug allocations')
    if const.unsupported_data:
        raise OwnedConstError('Owned CONST rejects iterated/reserved data')
    if any(p.segment == const.index for p in obj.publics.values()):
        raise OwnedConstError('Owned CONST may not have public aliases')
    if any(f.segment == const.index for f in obj.fixups):
        raise OwnedConstError('Owned CONST contribution must have no fixups')
    groups = []
    try:
        for kind, _, payload in obj.records:
            if kind != 0x9a:
                continue
            cursor = _Cursor(payload)
            name_index = cursor.index()
            if not 0 < name_index < len(obj.names):
                raise OwnedConstError('Owned CONST group has undefined name')
            members = []
            while cursor:
                if cursor.byte() != 0xff:
                    raise OwnedConstError('Owned CONST requires SEGDEF group components')
                member = cursor.index()
                if member not in obj.segments or member in members:
                    raise OwnedConstError('Owned CONST group member missing or repeated')
                members.append(member)
            groups.append({'index': len(groups) + 1, 'name': obj.names[name_index], 'segments': members})
    except OMFError as exc:
        raise OwnedConstError('Owned CONST malformed group: ' + str(exc)) from exc
    if (len(groups) != 1 or groups[0]['index'] != descriptor['group']
            or groups[0]['name'] != 'DGROUP' or const.index not in groups[0]['segments']
            or code.index in groups[0]['segments']
            or any(obj.segments[i].class_name not in ('CONST', 'DATA', 'BSS') for i in groups[0]['segments'])):
        raise OwnedConstError('Owned CONST requires one real matching DGROUP membership')
    data, writes = bytearray(), []
    for offset, content in sorted(const.chunks):
        if not content or offset != len(data) or offset + len(content) > const.length:
            raise OwnedConstError('Owned CONST has a hole/overlap/invalid complete LEDATA extent')
        data.extend(content)
        writes.append({'offset': offset, 'size': len(content), 'sha256': _sha(content)})
    if len(data) != const.length:
        raise OwnedConstError('Owned CONST has an uninitialized SEGDEF tail')
    fields = []
    for f in obj.fixups:
        if f.target != (0, const.index):
            continue
        if (f.segment != code.index or not info['offset'] <= f.offset or f.offset + f.width > info['end']
                or f.width != 2 or f.location_type != 1 or not f.segment_relative
                or f.frame != (1, descriptor['group']) or f.displacement not in (None, 0)):
            raise OwnedConstError('Owned CONST reference requires an owner CODE OFFSET16 DGROUP field')
        owning = [(start, chunk) for start, chunk in code.chunks if start <= f.offset and f.offset + 2 <= start + len(chunk)]
        if len(owning) != 1:
            raise OwnedConstError('Owned CONST reference field lacks one complete CODE write')
        start, chunk = owning[0]
        addend = int.from_bytes(chunk[f.offset - start:f.offset - start + 2], 'little')
        if not 0 <= addend + (f.displacement or 0) < const.length:
            raise OwnedConstError('Owned CONST reference addend leaves complete contribution')
        if any(abs(f.offset - item['object_offset']) < 2 for item in fields):
            raise OwnedConstError('Owned CONST reference fields overlap')
        fields.append({'object_offset': f.offset, 'function_offset': f.offset - info['offset'],
                       'width': f.width, 'location_type': f.location_type,
                       'segment_relative': f.segment_relative, 'frame': list(f.frame),
                       'target': list(f.target), 'displacement': f.displacement,
                       'original_addend': addend, 'record_offset': f.record_offset, 'raw_fixupp': f.raw.hex()})
    if not fields:
        raise OwnedConstError('Owned CONST lacks an actual owner CODE reference')
    project = Path(project).resolve()
    path = (project / descriptor['rea_evidence']).resolve()
    if not path.is_relative_to(project) or Path(descriptor['rea_evidence']).is_absolute():
        raise OwnedConstError('Owned CONST evidence must remain inside the matching project')
    data_unit = dict(descriptor, reference_region='exepack-expanded')
    try:
        frame, offset = validate_data_address(data_unit, reference)
        evidence_bytes = path.read_bytes()
        evidence = json.loads(evidence_bytes)
        evidence_id = validate_expanded_read(evidence, data_unit, bytes(data), reference)
    except (ValueError, KeyError, TypeError, OSError) as exc:
        raise OwnedConstError('Owned CONST primary/reference validation failed: ' + str(exc)) from exc
    provenance = {'classification': 'complete_compiler_owned_CONST_uncredited_context',
                  'authored_c_function_count': 0, 'source_data_credit': 0,
                  'segment': {k: v for k, v in asdict(const).items() if k != 'chunks'},
                  'group': groups[0], 'owner': {k: v for k, v in info.items() if k != 'fixups'},
                  'descriptor': descriptor, 'sha256': _sha(data), 'size': len(data),
                  'bytes_hex': bytes(data).hex(), 'data_writes': writes,
                  'code_references': sorted(fields, key=lambda f: f['object_offset']),
                  'rea_evidence_id': evidence_id, 'rea_evidence_sha256': _sha(evidence_bytes),
                  'original_sha256': reference['original_sha256'], 'carrier_sha256': reference['carrier_sha256'],
                  'data_frame': frame, 'data_offset': offset, 'complete_MZ_sites': [],
                  'requires_enclosing_CONST_alignment_context': bool(offset % 2),
                  'standalone_source_link_layout_proved': False,
                  'owner_CODE_SEGDEF_size': code.length,
                  'owner_CODE_bytes_outside_procedure': code.length - info['size'],
                  'omf_records_or_fields_modified': False}
    return descriptor, bytes(data), provenance
